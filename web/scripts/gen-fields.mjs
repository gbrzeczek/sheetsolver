// Writes src/lib/api/fields.generated.ts from openapi.json: for every
// input property (one with a `title`), its UI label, help text, default,
// bounds and option names. TypeScript types from openapi-typescript keep
// descriptions only as comments; the UI needs them at run time.
//
// The keys ("Saw.kerf", "Part.length", …) are the only way an input can
// ask for its label and help, so an input without help does not compile.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const openapi = JSON.parse(readFileSync(join(root, "openapi.json"), "utf8"));
const schemas = openapi.components.schemas;

const SCHEMAS = ["JobRequest", "Instance", "Saw", "Part", "Panel"];

/** The schema a property refers to, if any. */
function referenced(property) {
  const ref = property.$ref ?? property.allOf?.find((s) => s.$ref)?.$ref;
  return ref ? schemas[ref.split("/").pop()] : undefined;
}

const fields = {};
for (const schemaName of SCHEMAS) {
  const schema = schemas[schemaName];
  for (const [name, property] of Object.entries(schema.properties ?? {})) {
    if (!property.title) continue;
    if (!property.description) {
      throw new Error(`${schemaName}.${name} has a title but no description (help text)`);
    }
    const target = referenced(property);
    const options = target?.oneOf
      ?.filter((option) => "const" in option)
      .map((option) => ({ value: option.const, title: option.title }));
    fields[`${schemaName}.${name}`] = {
      label: property.title,
      help: property.description,
      ...(property.default !== undefined && { default: property.default }),
      ...(property.minimum !== undefined && { minimum: property.minimum }),
      ...(property.maximum !== undefined && { maximum: property.maximum }),
      ...(options?.length && { options }),
    };
  }
}

const out = `// Generated by scripts/gen-fields.mjs from openapi.json. Do not edit.

/** An input field's label, help text and limits, from \`docs/FIELDS.md\` via \`openapi.json\`. */
export interface ApiField {
  readonly label: string;
  readonly help: string;
  readonly default?: unknown;
  readonly minimum?: number;
  readonly maximum?: number;
  readonly options?: readonly { readonly value: string | number; readonly title: string }[];
}

export const API_FIELDS = ${JSON.stringify(fields, null, 2)} as const satisfies Record<string, ApiField>;

/** Every input field the API describes. */
export type ApiFieldKey = keyof typeof API_FIELDS;
`;
writeFileSync(join(root, "src/lib/api/fields.generated.ts"), out);
console.log(`fields.generated.ts: ${Object.keys(fields).length} fields`);
